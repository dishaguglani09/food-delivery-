const seedFoods = async () => {
  const mongoUri = process.env.MONGODB_URI;

  if (!mongoUri || mongoUri.includes('<username>') || mongoUri.includes('<password>')) {
    console.warn('[Seed Script] MONGODB_URI is not set. Seed data exported for in-memory use.');
    return;
  }

  try {
    console.log('[Seed Script] Connecting to MongoDB Atlas...');
    await mongoose.connect(mongoUri, { serverSelectionTimeoutMS: 5000 });
    console.log('[Seed Script] Connected. Clearing previous food collection...');

    await Food.deleteMany({});
    console.log('[Seed Script] Inserting authentic Indian menu items...');

    const createdFoods = await Food.insertMany(sampleFoods);
    console.log(`[Seed Script] ✅ Successfully seeded ${createdFoods.length} Indian culinary dishes!`);

    await mongoose.connection.close();
    process.exit(0);
  } catch (error) {
    console.error('[Seed Script] Error seeding database:', error.message);
    process.exit(1);
  }
};

if (require.main === module) {
  seedFoods();
}

module.exports = { sampleFoods, seedFoods };
